use super::{COUNT, checked, render};

fn colors() -> Vec<(u32, u32)> {
    (0..64)
        .rev()
        .map(|index| (index, 0xFF00_0000 | index))
        .collect()
}

#[test]
fn the_colours_are_in_index_order_without_their_first_two_digits() {
    let rows = checked(colors()).unwrap();
    assert_eq!(rows.len(), COUNT);
    assert_eq!(rows.first(), Some(&[0, 0, 0]));
    assert_eq!(rows.get(10), Some(&[0, 0, 10]));
    assert_eq!(rows.last(), Some(&[0, 0, 63]));
}

#[test]
fn another_count_or_an_index_given_twice_stops_the_generation() {
    let mut short = colors();
    short.pop();
    assert!(
        checked(short)
            .unwrap_err()
            .to_string()
            .contains("gives 63 indexed colours")
    );
    let mut twice = colors();
    twice.retain(|&(index, _)| index != 5);
    twice.push((4, 0));
    assert!(
        checked(twice)
            .unwrap_err()
            .to_string()
            .contains("no indexed colour 5")
    );
}

#[test]
fn the_table_is_one_row_per_colour_after_the_header() {
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &[[0, 0, 0], [255, 255, 255]],
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "\n",
            "/// The default indexed colours (ECMA-376 Part 1, section 18.8.27): red, green and blue of\n",
            "/// indexes 0 to 1.\n",
            "pub(super) static INDEXED_COLORS: [[u8; 3]; 2] = [\n",
            "    [0, 0, 0],\n",
            "    [255, 255, 255],\n",
            "];\n",
        )
    );
}
