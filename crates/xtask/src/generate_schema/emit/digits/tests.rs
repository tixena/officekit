use super::{render, zeros};
use crate::generate_schema::unicode_data::DecimalDigit;

/// The ten digits of the family whose zero is `zero`, named `{family} DIGIT {n}`.
fn family(zero: char, family: &str) -> Vec<DecimalDigit> {
    (0..10_u8)
        .map(|value| DecimalDigit {
            character: char::from_u32(u32::from(zero) + u32::from(value)).unwrap(),
            name: format!("{family} DIGIT {value}"),
            value,
        })
        .collect()
}

fn characters(found: &[&DecimalDigit]) -> Vec<char> {
    found.iter().map(|digit| digit.character).collect()
}

#[test]
fn the_zeros_of_the_families_are_sorted() {
    let mut digits = family('\u{FF10}', "FULLWIDTH");
    digits.extend(family('0', "ASCII"));
    digits.extend(family('\u{0660}', "ARABIC-INDIC"));
    assert_eq!(
        characters(&zeros(&digits).unwrap()),
        ['0', '\u{0660}', '\u{FF10}']
    );
}

#[test]
fn a_zero_without_its_nine_digits_stops_the_generation() {
    let mut digits = family('0', "ASCII");
    digits.remove(9);
    let err = zeros(&digits).unwrap_err();
    assert_eq!(
        err.to_string(),
        "ASCII DIGIT 0 is not followed by the digit 9"
    );
}

#[test]
fn a_digit_out_of_place_stops_the_generation() {
    let mut digits = family('0', "ASCII");
    digits[4].value = 5;
    let err = zeros(&digits).unwrap_err();
    assert_eq!(
        err.to_string(),
        "ASCII DIGIT 0 is not followed by the digit 4"
    );
}

#[test]
fn a_digit_in_no_family_stops_the_generation() {
    let mut digits = family('0', "ASCII");
    digits.push(DecimalDigit {
        character: '\u{0661}',
        name: "ARABIC-INDIC DIGIT ONE".to_owned(),
        value: 1,
    });
    let err = zeros(&digits).unwrap_err();
    assert_eq!(
        err.to_string(),
        "UnicodeData.txt gives 11 characters of category Nd, and 1 families of ten digits"
    );
}

#[test]
fn a_character_given_twice_stops_the_generation() {
    let mut digits = family('0', "ASCII");
    digits.push(digits[3].clone());
    let err = zeros(&digits).unwrap_err();
    assert_eq!(err.to_string(), "UnicodeData.txt gives ASCII DIGIT 3 twice");
}

#[test]
fn the_table_is_one_named_row_per_zero_after_the_header() {
    let ascii = family('0', "ASCII");
    let mathematical = family('\u{1D7CE}', "MATHEMATICAL BOLD");
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &[&ascii[0], &mathematical[0]],
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "\n",
            "/// The zero of each family of ten decimal digits (Unicode category `Nd`), sorted; a family's\n",
            "/// digit n is its zero's code point plus n.\n",
            "pub(super) static DIGIT_ZEROS: [char; 2] = [\n",
            "    '\\u{0030}',  // ASCII DIGIT 0\n",
            "    '\\u{1D7CE}', // MATHEMATICAL BOLD DIGIT 0\n",
            "];\n",
        )
    );
}
