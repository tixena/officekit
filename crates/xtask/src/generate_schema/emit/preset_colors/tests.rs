use super::{checked, render};

fn names(values: &[&str]) -> Vec<String> {
    values.iter().map(|value| (*value).to_owned()).collect()
}

fn colors(rows: &[(&str, [u8; 3])]) -> Vec<(String, [u8; 3])> {
    rows.iter()
        .map(|(name, rgb)| ((*name).to_owned(), *rgb))
        .collect()
}

#[test]
fn the_colours_are_sorted_by_name_when_they_give_each_value_once() {
    let given = colors(&[
        ("medOrchid", [186, 85, 211]),
        ("aliceBlue", [240, 248, 255]),
        ("mediumAquamarine", [102, 205, 170]),
    ]);
    let sorted = checked(
        given,
        &names(&["aliceBlue", "medOrchid", "mediumAquamarine"]),
    )
    .unwrap();
    assert_eq!(
        sorted,
        colors(&[
            ("aliceBlue", [240, 248, 255]),
            ("medOrchid", [186, 85, 211]),
            ("mediumAquamarine", [102, 205, 170]),
        ])
    );
}

#[test]
fn a_count_a_repeated_name_or_a_name_the_enumeration_lacks_stops_the_generation() {
    let values = names(&["aliceBlue", "black"]);
    let short = checked(colors(&[("black", [0, 0, 0])]), &values).unwrap_err();
    assert!(short.to_string().contains("gives 1 preset colours"));
    let twice = checked(
        colors(&[("black", [0, 0, 0]), ("black", [0, 0, 0])]),
        &values,
    )
    .unwrap_err();
    assert!(twice.to_string().contains("black twice"));
    let unknown = checked(
        colors(&[("black", [0, 0, 0]), ("aliceBlu", [240, 248, 255])]),
        &values,
    )
    .unwrap_err();
    assert!(unknown.to_string().contains("aliceBlu, which is no value"));
}

#[test]
fn the_table_is_one_row_per_colour_after_the_header() {
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &colors(&[("aliceBlue", [240, 248, 255]), ("black", [0, 0, 0])]),
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "\n",
            "/// The red, green and blue of each name of `ST_PresetColorVal` (ECMA-376 Part 1, section\n",
            "/// 20.1.10.48), sorted by name.\n",
            "pub(super) static PRESET_COLORS: [(&str, [u8; 3]); 2] = [\n",
            "    (\"aliceBlue\", [240, 248, 255]),\n",
            "    (\"black\", [0, 0, 0]),\n",
            "];\n",
        )
    );
}
