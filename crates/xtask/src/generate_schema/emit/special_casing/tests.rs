use super::{Tables, render, sorted};
use crate::generate_schema::unicode_data::{CasingContext, LanguageCasing};

fn casing(language: &str, character: char, lower: &str) -> LanguageCasing {
    LanguageCasing {
        character,
        contexts: Vec::new(),
        language: language.to_owned(),
        lower: lower.to_owned(),
        upper: character.to_string(),
    }
}

#[test]
fn the_rows_are_sorted_by_language_then_character() {
    let found = sorted(vec![
        casing("tr", 'I', "\u{131}"),
        casing("lt", '\u{CC}', "i\u{307}\u{300}"),
        casing("az", 'I', "\u{131}"),
        casing("tr", '\u{130}', "i"),
    ])
    .unwrap();
    let keys: Vec<(&str, char)> = found
        .iter()
        .map(|row| (row.language.as_str(), row.character))
        .collect();
    assert_eq!(
        keys,
        [
            ("az", 'I'),
            ("lt", '\u{CC}'),
            ("tr", 'I'),
            ("tr", '\u{130}')
        ]
    );
}

#[test]
fn a_row_given_twice_stops_the_generation() {
    let err = sorted(vec![casing("tr", 'I', "\u{131}"), casing("tr", 'I', "i")]).unwrap_err();
    assert_eq!(err.to_string(), "SpecialCasing.txt gives tr U+0049 twice");
}

#[test]
fn no_row_stops_the_generation() {
    let err = sorted(Vec::new()).unwrap_err();
    assert_eq!(
        err.to_string(),
        "SpecialCasing.txt gives no language a mapping"
    );
}

#[test]
fn the_table_is_the_three_statics_after_the_header() {
    let mut dotless = casing("tr", 'I', "\u{131}");
    dotless.contexts = vec![(CasingContext::BeforeDot, false)];
    let tables = Tables {
        casings: vec![dotless, casing("tr", 'i', "i")],
        classes: vec![('\u{300}', '\u{314}', 230), ('\u{315}', '\u{315}', 232)],
        soft_dotted: vec![('i', 'j')],
    };
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &tables,
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "// Derived from Unicode data; the Unicode License v3 notice is in the crate's LICENSE-UNICODE.\n",
            "\n",
            "//! The Unicode Character Database's case mappings of a language, and the properties their contexts\n",
            "//! read.\n",
            "\n",
            "use super::{Casing, Context};\n",
            "\n",
            "/// Each mapping `SpecialCasing.txt` gives a language, sorted by language and character.\n",
            "pub(super) static CASE_BY_LANGUAGE: [Casing; 2] = [\n",
            "    Casing {\n",
            "        character: '\\u{49}',\n",
            "        contexts: &[(Context::BeforeDot, false)],\n",
            "        language: \"tr\",\n",
            "        lower: \"\\u{131}\",\n",
            "        upper: \"I\",\n",
            "    },\n",
            "    Casing {\n",
            "        character: '\\u{69}',\n",
            "        contexts: &[],\n",
            "        language: \"tr\",\n",
            "        lower: \"i\",\n",
            "        upper: \"i\",\n",
            "    },\n",
            "];\n",
            "\n",
            "/// Each range of characters whose canonical combining class is not 0, and the class, sorted.\n",
            "pub(super) static COMBINING_CLASSES: [(char, char, u8); 2] = [\n",
            "    ('\\u{300}', '\\u{314}', 230),\n",
            "    ('\\u{315}', '\\u{315}', 232),\n",
            "];\n",
            "\n",
            "/// Each range of characters with the property `Soft_Dotted`, sorted.\n",
            "pub(super) static SOFT_DOTTED: [(char, char); 1] = [\n",
            "    ('\\u{69}', '\\u{6a}'),\n",
            "];\n",
        )
    );
}
