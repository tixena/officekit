use super::{checked, emu, render, table, unstated};
use crate::generate_schema::standard_text::{Paper, PaperUnit};

const LETTER_ROTATED: &str = concat!(
    "[[paper]]\n",
    "code = 75\n",
    "width = \"11\"\n",
    "height = \"8.5\"\n",
    "unit = \"in\"\n",
    "reason = \"the rotated pair of code 1\"\n",
);

fn paper(code: u32, width: &str, height: &str, unit: PaperUnit) -> Paper {
    Paper {
        code,
        height: (height.to_owned(), unit),
        width: (width.to_owned(), unit),
    }
}

#[test]
fn an_inch_and_a_millimetre_are_whole_counts_of_emu() {
    assert_eq!(emu("8.5", PaperUnit::Inch).unwrap(), 7_772_400);
    assert_eq!(emu("3.875", PaperUnit::Inch).unwrap(), 3_543_300);
    assert_eq!(emu("11.69", PaperUnit::Inch).unwrap(), 10_689_336);
    assert_eq!(emu("210", PaperUnit::Millimetre).unwrap(), 7_560_000);
    assert!(
        emu("0.00001", PaperUnit::Millimetre)
            .unwrap_err()
            .to_string()
            .contains("no whole count of EMU")
    );
}

#[test]
fn the_rows_are_sorted_by_code_and_a_code_given_twice_stops_the_generation() {
    let rows = checked(&[
        paper(9, "210", "297", PaperUnit::Millimetre),
        paper(1, "8.5", "11", PaperUnit::Inch),
    ])
    .unwrap();
    assert_eq!(
        rows,
        [(1, 7_772_400, 10_058_400), (9, 7_560_000, 10_692_000)]
    );
    let twice = checked(&[
        paper(1, "8.5", "11", PaperUnit::Inch),
        paper(1, "8.5", "11", PaperUnit::Inch),
    ])
    .unwrap_err();
    assert!(twice.to_string().contains("code 1 twice"));
    assert!(
        checked(&[])
            .unwrap_err()
            .to_string()
            .contains("no paper size")
    );
}

#[test]
fn the_table_is_one_row_per_paper_after_the_header() {
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &[(1, 7_772_400, 10_058_400), (70, 3_780_000, 5_328_000)],
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "\n",
            "/// The width and the height in EMU of each paper code that ECMA-376 Part 1, section 18.3.1.63,\n",
            "/// gives a size, sorted by code.\n",
            "pub(super) static PAPER_SIZES: [(u32, i64, i64); 2] = [\n",
            "    (1, 7_772_400, 10_058_400),\n",
            "    (70, 3_780_000, 5_328_000),\n",
            "];\n",
        )
    );
}

/// Section 18.3.1.63 of Part 1 with code 1 and the line `75` writes.
fn section(code_75: &str) -> String {
    format!(
        concat!(
            "18.3.1.63         pageSetup (Page Setup Settings)\n",
            "paperSize (Paper      Paper size\n",
            "Size)                 1 = Letter paper (8.5 in. by 11 in.)\n",
            "             {}\n",
            "18.3.1.64         pageSetup (Chart Sheet Page Setup)\n",
        ),
        code_75
    )
}

#[test]
fn a_code_the_section_gives_no_size_takes_its_size_from_the_data() {
    let rows = table(
        &section("75 = Letter Rotated (11in x 8 1/2 11 in)"),
        LETTER_ROTATED,
    )
    .unwrap();
    assert_eq!(
        rows,
        [(1, 7_772_400, 10_058_400), (75, 10_058_400, 7_772_400)]
    );
}

#[test]
fn a_code_the_section_gives_a_size_and_the_data_names_stops_the_generation() {
    let error = table(
        &section("75 = Letter Rotated (11 in x 8.5 in)"),
        LETTER_ROTATED,
    )
    .unwrap_err();
    assert!(
        error
            .to_string()
            .contains("gives a size for the paper code 75")
    );
}

#[test]
fn a_row_of_the_data_without_its_reason_or_with_an_unknown_unit_stops_the_generation() {
    let without_reason = LETTER_ROTATED.replace("reason = \"the rotated pair of code 1\"\n", "");
    assert!(
        unstated(&without_reason)
            .unwrap_err()
            .to_string()
            .contains("without `reason`")
    );
    let in_points = LETTER_ROTATED.replace("unit = \"in\"", "unit = \"pt\"");
    assert!(
        unstated(&in_points)
            .unwrap_err()
            .to_string()
            .contains("has the unit pt")
    );
}

#[test]
fn a_section_with_no_paper_stops_the_generation_whatever_the_data_adds() {
    assert!(
        table("", LETTER_ROTATED)
            .unwrap_err()
            .to_string()
            .contains("no paper size")
    );
}
