use super::{checked, emu, render};
use crate::generate_schema::standard_text::{Paper, PaperUnit};

fn paper(code: u32, width: &str, height: &str, unit: PaperUnit) -> Paper {
    Paper {
        code,
        height: (height.to_owned(), unit),
        width: (width.to_owned(), unit),
    }
}

#[test]
fn an_inch_and_a_millimetre_are_whole_counts_of_emu() {
    assert_eq!(emu("8.5", PaperUnit::Inch).unwrap(), 7_772_400);
    assert_eq!(emu("3.875", PaperUnit::Inch).unwrap(), 3_543_300);
    assert_eq!(emu("11.69", PaperUnit::Inch).unwrap(), 10_689_336);
    assert_eq!(emu("210", PaperUnit::Millimetre).unwrap(), 7_560_000);
    assert!(
        emu("0.00001", PaperUnit::Millimetre)
            .unwrap_err()
            .to_string()
            .contains("no whole count of EMU")
    );
}

#[test]
fn the_rows_are_sorted_by_code_and_a_code_given_twice_stops_the_generation() {
    let rows = checked(&[
        paper(9, "210", "297", PaperUnit::Millimetre),
        paper(1, "8.5", "11", PaperUnit::Inch),
    ])
    .unwrap();
    assert_eq!(
        rows,
        [(1, 7_772_400, 10_058_400), (9, 7_560_000, 10_692_000)]
    );
    let twice = checked(&[
        paper(1, "8.5", "11", PaperUnit::Inch),
        paper(1, "8.5", "11", PaperUnit::Inch),
    ])
    .unwrap_err();
    assert!(twice.to_string().contains("code 1 twice"));
    assert!(
        checked(&[])
            .unwrap_err()
            .to_string()
            .contains("no paper size")
    );
}

#[test]
fn the_table_is_one_row_per_paper_after_the_header() {
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &[(1, 7_772_400, 10_058_400), (70, 3_780_000, 5_328_000)],
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "\n",
            "/// The width and the height in EMU of each paper code that ECMA-376 Part 1, section 18.3.1.63,\n",
            "/// gives a size, sorted by code.\n",
            "pub(super) static PAPER_SIZES: [(u32, i64, i64); 2] = [\n",
            "    (1, 7_772_400, 10_058_400),\n",
            "    (70, 3_780_000, 5_328_000),\n",
            "];\n",
        )
    );
}
