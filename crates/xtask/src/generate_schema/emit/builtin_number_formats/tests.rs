use super::{COUNT, checked, render};

fn formats(count: u32) -> Vec<(u32, String)> {
    (0..count)
        .rev()
        .map(|id| (id, format!("code {id}")))
        .collect()
}

#[test]
fn the_formats_are_sorted_by_id_when_the_list_gives_twenty_eight() {
    let sorted = checked(formats(28)).unwrap();
    assert_eq!(sorted.len(), COUNT);
    assert_eq!(sorted.first(), Some(&(0, "code 0".to_owned())));
    assert_eq!(sorted.last(), Some(&(27, "code 27".to_owned())));
}

#[test]
fn another_count_or_an_id_given_twice_stops_the_generation() {
    let short = checked(formats(27)).unwrap_err();
    assert!(
        short
            .to_string()
            .contains("gives 27 built-in number formats")
    );
    let mut twice = formats(27);
    twice.push((3, "0".to_owned()));
    assert!(
        checked(twice)
            .unwrap_err()
            .to_string()
            .contains("id 3 twice")
    );
}

#[test]
fn the_table_is_one_row_per_format_with_each_code_quoted() {
    let text = render(
        "// Generated by `cargo xtask generate-schema`; do not edit.\n",
        &[(0, "General".to_owned()), (49, "\"x\"\\@".to_owned())],
    );
    assert_eq!(
        text,
        concat!(
            "// Generated by `cargo xtask generate-schema`; do not edit.\n",
            "\n",
            "/// The format code of each built-in number format id of the list \"All Languages\" (ECMA-376\n",
            "/// Part 1, section 18.8.30), sorted by id.\n",
            "pub(super) static BUILTIN_FORMATS: [(u32, &str); 2] = [\n",
            "    (0, \"General\"),\n",
            "    (49, \"\\\"x\\\"\\\\@\"),\n",
            "];\n",
        )
    );
}
