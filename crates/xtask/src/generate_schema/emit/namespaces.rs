//! The namespace table: one row per namespace officekit knows, written to
//! `crates/officekit-xml/src/name/table.rs`.

use alloc::collections::{BTreeMap, BTreeSet};
use core::fmt::{self, Write as _};
use std::ffi::OsStr;
use std::path::{Path, PathBuf};

use anyhow::{Context as _, Result, bail};
use officekit_xml::ready::ready_now;
use os_shim::System;
use os_shim::bucket::Condition;
use sha2::{Digest as _, Sha256};

use crate::generate_schema::inputs::Inputs;
use crate::generate_schema::model::SchemaSet;
use crate::generate_schema::sdk_data::{DataVersion, SdkData};

#[cfg(test)]
mod tests;

/// Where the table is written, from the workspace root.
pub const TABLE_PATH: &str = "crates/officekit-xml/src/name/table.rs";

/// `NamespaceId` is a `u8`, so the table holds at most this many rows.
const MAX_ROWS: usize = 256;

/// One row of the table.
#[derive(Clone, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub struct Row {
    /// The Office version that brought a Microsoft extension; `None` for ECMA-376's own.
    pub introduced: Option<DataVersion>,
    pub prefix: String,
    /// The Strict URI, when the namespace has one apart from its Transitional URI.
    pub strict_uri: Option<String>,
    /// The Transitional URI, or the only one.
    pub uri: String,
}

/// What was written.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub struct Summary {
    /// Rows dated Office 2010 or later.
    pub introduced: usize,
    pub rows: usize,
    /// Rows with a Strict URI.
    pub strict_uris: usize,
}

/// Read the inputs, build the table, and write it to `out`.
///
/// # Errors
///
/// An input that cannot be read, a namespace the rows cannot be built for, a
/// table past `NamespaceId`'s range, or an output that cannot be written.
pub fn emit<S>(system: &S, inputs: &Inputs, out: &Path) -> Result<Summary>
where
    S: System + ?Sized,
{
    let data = SdkData::read(system, &inputs.sdk_data)?;
    let transitional = SchemaSet::read(system, &inputs.transitional_schemas)?;
    let strict = SchemaSet::read(system, &inputs.strict_schemas)?;
    let open_specifications: Vec<&PathBuf> = inputs
        .open_specifications
        .iter()
        .map(|(_, path)| path)
        .collect();
    let open = SchemaSet::read(system, &open_specifications)?;
    let rows = rows(&data, &transitional, &strict, &open)?;

    let mut read: Vec<PathBuf> = inputs.strict_schemas.clone();
    read.extend(inputs.transitional_schemas.iter().cloned());
    read.extend(open_specifications.into_iter().cloned());
    read.push(inputs.sdk_data.join("namespaces.json"));
    let text = render(
        &header(inputs.checksums(), inputs.tools(), &read, &[])?,
        &rows,
    );

    if let Some(parent) = out.parent() {
        ready_now(system.create_dir_all(parent))
            .with_context(|| format!("cannot create {}", parent.display()))?;
    }
    ready_now(system.write(out, text.as_bytes(), Condition::None))
        .with_context(|| format!("cannot write {}", out.display()))?;
    Ok(Summary {
        introduced: rows.iter().filter(|row| row.introduced.is_some()).count(),
        rows: rows.len(),
        strict_uris: rows.iter().filter(|row| row.strict_uri.is_some()).count(),
    })
}

/// The comment that starts every generated file: the inputs with their
/// `SHA256SUMS` lines, the committed `tables` with their computed SHA-256
/// sorted by path, then the `TOOLS` lines.
///
/// # Errors
///
/// An input with no line in `checksums`.
pub fn header(
    checksums: &str,
    tools: &str,
    inputs: &[PathBuf],
    tables: &[(&Path, &[u8])],
) -> Result<String> {
    let mut lines = vec![
        "// Generated by `cargo xtask generate-schema`; do not edit.".to_owned(),
        "// Inputs:".to_owned(),
    ];
    for input in inputs {
        let shown = input.display().to_string();
        let sum = checksums
            .lines()
            .find(|line| line.split_once("  ").is_some_and(|(_, path)| path == shown))
            .with_context(|| format!("{shown} has no line in SHA256SUMS"))?;
        lines.push(format!("//   {sum}"));
    }
    let mut sorted = tables.to_vec();
    sorted.sort_by_key(|(path, _)| *path);
    for (path, bytes) in sorted {
        lines.push(format!(
            "//   {}  {}",
            hex(&Sha256::digest(bytes)),
            path.display()
        ));
    }
    lines.extend(tools.lines().map(|line| format!("// {line}")));
    lines.push(String::new());
    Ok(lines.join("\n"))
}

/// Bytes as lowercase hexadecimal.
fn hex(bytes: &[u8]) -> String {
    let mut text = String::new();
    for byte in bytes {
        let _: fmt::Result = write!(text, "{byte:02x}");
    }
    text
}

/// The Office version as the table spells it; Office 2007 is ECMA-376's own.
const fn introduced(version: Option<DataVersion>) -> Option<&'static str> {
    match version {
        None | Some(DataVersion::Office2007) => None,
        Some(DataVersion::Microsoft365) => Some("Microsoft365"),
        Some(DataVersion::Office2010) => Some("Office2010"),
        Some(DataVersion::Office2013) => Some("Office2013"),
        Some(DataVersion::Office2016) => Some("Office2016"),
        Some(DataVersion::Office2019) => Some("Office2019"),
        Some(DataVersion::Office2021) => Some("Office2021"),
    }
}

/// A prefix the Transitional schemas bind to `uri`.
fn declared_prefix(transitional: &SchemaSet, uri: &str) -> Result<String> {
    transitional
        .namespaces
        .values()
        .flat_map(|file| &file.prefixes)
        .filter(|(prefix, bound)| !prefix.is_empty() && bound.as_str() == uri)
        .map(|(prefix, _)| prefix.clone())
        .collect::<BTreeSet<String>>()
        .into_iter()
        .next()
        .with_context(|| format!("no prefix is known for the namespace {uri}"))
}

/// The table's text: `header`, then the rows.
#[must_use]
pub fn render(header: &str, rows: &[Row]) -> String {
    let body = rows
        .iter()
        .map(|row| {
            let strict = row
                .strict_uri
                .as_ref()
                .map_or_else(|| "None".to_owned(), |uri| format!("Some({uri:?})"));
            let version = introduced(row.introduced).map_or_else(
                || "None".to_owned(),
                |name| format!("Some(OfficeVersion::{name})"),
            );
            format!(
                "    NamespaceRow {{\n        introduced: {version},\n        prefix: {:?},\n        \
                 strict_uri: {strict},\n        uri: {:?},\n    }},\n",
                row.prefix, row.uri,
            )
        })
        .collect::<Vec<String>>()
        .concat();
    format!(
        "{header}\n//! The namespaces officekit knows.\n//!\n\
         //! A namespace is the group an element or attribute name belongs to. Each has a prefix,\n\
         //! such as `w` for Word's, and a URI that files use to name it. A file in the Strict\n\
         //! class may use another URI for the same namespace. `NAMESPACES` holds one row for each,\n\
         //! and `NamespaceRow` is a row.\n\
         \nuse super::OfficeVersion;\n\n\
         /// Every namespace, sorted by prefix; a namespace's id is its index. A name that holds\n\
         /// `Namespace::Known` holds this id.\n\
         pub static NAMESPACES: &[NamespaceRow] = &[\n{body}];\n\n\
         /// A namespace officekit knows.\n\
         #[non_exhaustive]\n\
         pub struct NamespaceRow {{\n\
         \x20   /// The Office version that brought a Microsoft extension; `None` for ECMA-376's own.\n\
         \x20   pub introduced: Option<OfficeVersion>,\n\
         \x20   /// The prefix the schemas bind to the namespace, such as `w`.\n\
         \x20   pub prefix: &'static str,\n\
         \x20   /// The Strict URI, when the namespace has one apart from its Transitional URI.\n\
         \x20   pub strict_uri: Option<&'static str>,\n\
         \x20   /// The Transitional URI, or the only one.\n\
         \x20   pub uri: &'static str,\n\
         }}\n"
    )
}

/// Every namespace of the SDK data, then the Transitional namespaces it lacks,
/// each with the Strict URI of its twin; sorted by prefix.
///
/// # Errors
///
/// A Strict file with no Transitional file of its name, a Transitional
/// namespace outside the data with no prefix declared for it, an Open
/// Specifications namespace outside the data (no version is known for it), a
/// prefix used twice, or more rows than `NamespaceId` holds.
pub fn rows(
    data: &SdkData,
    transitional: &SchemaSet,
    strict: &SchemaSet,
    open: &SchemaSet,
) -> Result<Vec<Row>> {
    let by_file: BTreeMap<&OsStr, &String> = transitional
        .namespaces
        .iter()
        .filter_map(|(uri, file)| Some((file.path.file_name()?, uri)))
        .collect();
    let mut twins: BTreeMap<&String, &String> = BTreeMap::new();
    for (strict_uri, file) in &strict.namespaces {
        let twin = file
            .path
            .file_name()
            .and_then(|name| by_file.get(name))
            .with_context(|| {
                format!(
                    "the Strict file {} has no Transitional file of its name",
                    file.path.display()
                )
            })?;
        twins.insert(*twin, strict_uri);
    }

    let mut rows: Vec<Row> = data
        .namespaces
        .iter()
        .filter(|namespace| !namespace.uri.is_empty())
        .map(|namespace| Row {
            introduced: namespace
                .version
                .filter(|version| *version != DataVersion::Office2007),
            prefix: namespace.prefix.clone(),
            strict_uri: twins.get(&namespace.uri).map(|uri| (*uri).clone()),
            uri: namespace.uri.clone(),
        })
        .collect();
    let known: BTreeSet<String> = rows.iter().map(|row| row.uri.clone()).collect();
    for uri in transitional
        .namespaces
        .keys()
        .filter(|uri| !known.contains(*uri))
    {
        rows.push(Row {
            introduced: None,
            prefix: declared_prefix(transitional, uri)?,
            strict_uri: twins.get(uri).map(|strict_uri| (*strict_uri).clone()),
            uri: uri.clone(),
        });
    }
    if let Some(uri) = open
        .namespaces
        .keys()
        .find(|uri| !rows.iter().any(|row| &row.uri == *uri))
    {
        bail!(
            "the Open Specifications namespace {uri} is not in namespaces.json: no Office version is known for it"
        );
    }

    rows.sort_by(|left, right| left.prefix.cmp(&right.prefix));
    if let Some((first, second)) = rows
        .iter()
        .zip(rows.iter().skip(1))
        .find(|(first, second)| first.prefix == second.prefix)
    {
        bail!(
            "the prefix {} is used by {} and {}",
            first.prefix,
            first.uri,
            second.uri,
        );
    }
    if rows.len() > MAX_ROWS {
        bail!(
            "the table has {} rows but NamespaceId is a u8 and holds {MAX_ROWS}: widen NamespaceId",
            rows.len(),
        );
    }
    Ok(rows)
}
